/// The keyboards' clipboard history, like Gboard's (#597): one store in the App Group's
/// container, so the English and Bulgarian keyboards share it. Newest first, one row per
/// text or image (the same again moves up), at most `cap` unpinned, and none older than
/// `maxAge` unless pinned. Nothing stays in memory between calls: each reads and rewrites
/// `index.json`, so neither extension holds a stale copy. Images are files, downsampled to
/// `imageSide` on the way in and decoded only as thumbnails (the extension's memory cap).
///
/// What goes in, never with an Allow Paste prompt: each clip pasted through the keyboard's
/// own Paste controls (the bar's, the toolbar's, and the panel's, which takes images too),
/// and the keyboard's own copies (copy and cut line). Reading the pasteboard unasked raises
/// Allow Paste, so a clip copied elsewhere shows only as the panel's Paste (`fresh`), and
/// only the latest: a keyboard runs only while it shows. With Save Copies Automatically (on by
/// default) the keyboard reads it unasked (`save`, #601): silent only where iOS allows
/// Prosper to paste from other apps.
/// Clips marked concealed or transient (password managers) never go in.
final class ClipboardHistory {
    struct Clip: Codable, Equatable, Identifiable {
        var id = UUID()
        var text: String?
        /// The image's file in `dir`, named for its bytes' hash: the same image is one file.
        var image: String?
        var date: Date
        var pinned = false
    }

    private struct Index: Codable, Equatable {
        var clips: [Clip] = []
        /// The pasteboard `changeCount` last kept or written: that clip isn't offered again.
        var change: Int?
    }

    /// Types password managers and the like mark a clip with: never kept.
    static let concealed: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                         "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
    /// ponytail: longer text isn't kept, so the index stays small to read on every open.
    static let textLimit = 20_000
    static let imageSide: CGFloat = 1024

    let dir: URL
    let cap: Int
    let maxAge: TimeInterval
    var now: () -> Date = Date.init

    init(dir: URL, cap: Int = 50, maxAge: TimeInterval = 30 * 86_400) {
        self.dir = dir
        self.cap = cap
        self.maxAge = maxAge
    }

    /// The App Group's store, nil where the container isn't there.
    static func shared() -> ClipboardHistory? {
        FileManager.default.containerURL(forSecurityApplicationGroupIdentifier: KeyboardSettings.suiteName)
            .map { ClipboardHistory(dir: $0.appendingPathComponent("ClipboardHistory", isDirectory: true)) }
    }

    var clips: [Clip] { update().clips }

    /// No concealed type, and not the clip last kept: prompt-free reads only.
    func capturable(_ pb: UIPasteboard) -> Bool {
        pb.changeCount != update().change && Self.concealed.isDisjoint(with: pb.types)
    }

    /// The panel offers its Paste: a text or image clip not kept yet.
    func fresh(_ pb: UIPasteboard) -> Bool { (pb.hasStrings || pb.hasImages) && capturable(pb) }

    /// A clip the keyboard pasted or copied, as `pb` holds it now. Over `base`, the rows a
    /// cut line's first batch found, a later batch's text takes the last's place: one row a
    /// cut (#597 QA: each batch kept its own). Returns the base for the next batch.
    @discardableResult
    func record(_ text: String, from pb: UIPasteboard, over base: [Clip]? = nil) -> [Clip]? {
        guard capturable(pb) else { return base }
        let base = base ?? clips
        keep(text: text, change: pb.changeCount, over: base)
        return base
    }

    /// A clip copied elsewhere, read unasked (#601): its text, or else its image, kept as the
    /// panel's Paste keeps them. Refused (Allow Paste's Don't Allow), the read finds nothing and
    /// the clip stays `fresh`, for the panel's Paste.
    func save(_ pb: UIPasteboard) {
        guard fresh(pb) else { return }
        let change = pb.changeCount
        let clip = read(pb)
        if let text = clip.text {
            keep(text: text, change: change)
        } else if let name = clip.image.flatMap({ storeImage(Self.source($0 as CFData)) }) {
            keep(Clip(image: name, date: now()), change: change)
        }
    }

    /// `save`'s one read, the one that raises Allow Paste: plain text, or else an image's
    /// bytes. Settable for tests.
    var read: (UIPasteboard) -> (text: String?, image: Data?) = { pb in
        let conforming = { (type: UTType) in pb.types.first { UTType($0)?.conforms(to: type) == true } }
        if conforming(.plainText) != nil { return (pb.string, nil) }
        return (nil, conforming(.image).flatMap(pb.data(forPasteboardType:)))
    }

    /// The panel's Paste: its clip, text or else an image, kept; then `done`, on the main queue.
    /// Text only as plain text: NSString also loads a file URL, as its path.
    func capture(_ providers: [NSItemProvider], from pb: UIPasteboard, done: @escaping () -> Void = {}) {
        guard capturable(pb), let p = providers.first else { return }
        let change = pb.changeCount
        if p.hasItemConformingToTypeIdentifier(UTType.plainText.identifier) {
            _ = p.loadObject(ofClass: NSString.self) { s, _ in
                DispatchQueue.main.async {
                    if let s = s as? String { self.keep(text: s, change: change) }
                    done()
                }
            }
        } else if let type = p.registeredTypeIdentifiers.first(where: { UTType($0)?.conforms(to: .image) == true }) {
            _ = p.loadFileRepresentation(forTypeIdentifier: type) { url, _ in
                let name = url.flatMap(self.storeImage(at:))   // the file lives only in this callback
                DispatchQueue.main.async {
                    if let name { self.keep(Clip(image: name, date: self.now()), change: change) }
                    done()
                }
            }
        }
    }

    /// `clip` on `pb`: text as a string, an image as its file's bytes. That clip isn't offered
    /// again (`fresh`), nor is it kept anew.
    @discardableResult
    func copy(_ clip: Clip, to pb: UIPasteboard) -> Bool {
        if let text = clip.text {
            pb.string = text
        } else if let name = clip.image, let data = try? Data(contentsOf: url(name)),
                  let type = UTType(filenameExtension: url(name).pathExtension) {
            pb.setData(data, forPasteboardType: type.identifier)
        } else {
            return false
        }
        let change = pb.changeCount
        update { $0.change = change }
        return true
    }

    func pin(_ id: UUID, _ on: Bool) {
        update { i in if let k = i.clips.firstIndex(where: { $0.id == id }) { i.clips[k].pinned = on } }
    }

    func delete(_ id: UUID) { update { $0.clips.removeAll { $0.id == id } } }

    /// Clear all: the pinned stay.
    func clear() { update { $0.clips.removeAll { !$0.pinned } } }

    /// A thumbnail `side` pixels at most, decoded from the file only now.
    func thumbnail(_ clip: Clip, side: CGFloat) -> UIImage? {
        guard let name = clip.image, let cg = Self.downsample(Self.source(url(name)), side: side) else { return nil }
        return UIImage(cgImage: cg)
    }

    /// The image at `source` downsampled to `imageSide`, as PNG if it has alpha, else JPEG,
    /// in `dir`: its file's name, nil if it isn't an image.
    func storeImage(at source: URL) -> String? { storeImage(Self.source(source)) }

    private func storeImage(_ source: CGImageSource?) -> String? {
        guard let cg = Self.downsample(source, side: Self.imageSide) else { return nil }
        let alpha = ![.none, .noneSkipFirst, .noneSkipLast].contains(cg.alphaInfo)
        let type: UTType = alpha ? .png : .jpeg
        let data = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(data, type.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dest, cg, [kCGImageDestinationLossyCompressionQuality: 0.85] as CFDictionary)
        guard CGImageDestinationFinalize(dest) else { return nil }
        let hash = SHA256.hash(data: data as Data).prefix(16).map { String(format: "%02x", $0) }.joined()
        let name = hash + "." + (type.preferredFilenameExtension ?? "img")
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        guard (try? (data as Data).write(to: url(name), options: .atomic)) != nil else { return nil }
        return name
    }

    func url(_ name: String) -> URL { dir.appendingPathComponent(name) }

    private static func source(_ url: URL) -> CGImageSource? {
        CGImageSourceCreateWithURL(url as CFURL, [kCGImageSourceShouldCache: false] as CFDictionary)
    }

    private static func source(_ data: CFData) -> CGImageSource? {
        CGImageSourceCreateWithData(data, [kCGImageSourceShouldCache: false] as CFDictionary)
    }

    private static func downsample(_ src: CGImageSource?, side: CGFloat) -> CGImage? {
        guard let src else { return nil }
        return CGImageSourceCreateThumbnailAtIndex(src, 0, [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: side,
        ] as CFDictionary)
    }

    /// Blank or too long isn't kept, but isn't offered again either (#597 QA: a blank Paste stayed).
    private func keep(text: String, change: Int, over base: [Clip]? = nil) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf16.count <= Self.textLimit else { update { $0.clips = base ?? $0.clips; $0.change = change }; return }
        keep(Clip(text: text, date: now()), change: change, over: base)
    }

    /// `clip` on top, over `base` if given; the same text or image goes from lower down, its pin with it.
    private func keep(_ clip: Clip, change: Int, over base: [Clip]? = nil) {
        update { i in
            i.clips = base ?? i.clips
            var clip = clip
            clip.pinned = i.clips.contains { $0.pinned && $0.text == clip.text && $0.image == clip.image }
            i.clips.removeAll { $0.text == clip.text && $0.image == clip.image }
            i.clips.insert(clip, at: 0)
            i.change = change
        }
    }

    private var indexURL: URL { url("index.json") }

    /// Read, `change`, then age out and cap the unpinned, drop the files no clip names, and
    /// write back if anything changed.
    @discardableResult
    private func update(_ change: (inout Index) -> Void = { _ in }) -> Index {
        let old = (try? Data(contentsOf: indexURL)).flatMap { try? JSONDecoder().decode(Index.self, from: $0) } ?? Index()
        var index = old
        change(&index)
        let cutoff = now().addingTimeInterval(-maxAge)
        var unpinned = 0
        index.clips = index.clips.filter { c in
            if c.pinned { return true }
            unpinned += 1
            return unpinned <= cap && c.date > cutoff
        }
        guard index != old else { return index }
        for name in Set(old.clips.compactMap(\.image)).subtracting(index.clips.compactMap(\.image)) {
            try? FileManager.default.removeItem(at: url(name))
        }
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        try? JSONEncoder().encode(index).write(to: indexURL, options: .atomic)
        return index
    }
}

/// A panel in the keys' place, over the keyboard's keys (`SuggestionBar.cover`) or the
/// terminal (`TerminalHostVC.cover`): a header with the way back, its title and `trailing`,
/// a table, and a note while that's empty. The clipboard history's and the snippets' (#609).
/// In the theme's colours (#626): its rows on a card with hairline separators (`card`), the
/// table itself, as tall as its rows up to 8 pt above the panel's bottom, then scrolling.
class KeysPanel: UIView {
    typealias Style = TerminalKeyboard.Style
    var onClose: (() -> Void)?
    let table: UITableView = Card(frame: .zero, style: .plain)
    let backButton = UIButton(configuration: .plain())
    let title = UILabel()
    let empty = UILabel()

    init(title text: String, empty note: String, trailing: [UIView] = []) {
        super.init(frame: .zero)
        backgroundColor = Style.backdrop
        overrideUserInterfaceStyle = Style.palette.style

        backButton.configuration?.image = UIImage(systemName: "keyboard")
        backButton.configuration?.baseForegroundColor = Style.icon
        backButton.accessibilityLabel = "Back to the keys"
        backButton.addAction(UIAction { [weak self] _ in self?.onClose?() }, for: .touchUpInside)
        title.text = text
        title.font = .systemFont(ofSize: 15, weight: .semibold)
        title.textColor = Style.label
        let header = UIStackView(arrangedSubviews: [backButton, title, UIView()] + trailing)
        header.spacing = 6
        header.alignment = .center

        table.backgroundColor = Style.surface
        table.separatorColor = Style.hairline
        table.layer.cornerRadius = 14
        table.tableFooterView = UIView(frame: CGRect(x: 0, y: 0, width: 0, height: 1))   // no separator under the last row
        table.rowHeight = UITableView.automaticDimension
        table.estimatedRowHeight = 52
        empty.text = note
        empty.textColor = Style.hint
        empty.font = .systemFont(ofSize: 14)
        empty.numberOfLines = 0
        empty.textAlignment = .center
        for v in [header, table, empty] {
            v.translatesAutoresizingMaskIntoConstraints = false
            addSubview(v)
        }
        NSLayoutConstraint.activate([
            header.topAnchor.constraint(equalTo: topAnchor, constant: 2),
            header.leadingAnchor.constraint(equalTo: safeAreaLayoutGuide.leadingAnchor, constant: 4),
            header.trailingAnchor.constraint(equalTo: safeAreaLayoutGuide.trailingAnchor, constant: -4),
            header.heightAnchor.constraint(equalToConstant: 40),
            table.topAnchor.constraint(equalTo: header.bottomAnchor),
            table.leadingAnchor.constraint(equalTo: safeAreaLayoutGuide.leadingAnchor, constant: 8),
            table.trailingAnchor.constraint(equalTo: safeAreaLayoutGuide.trailingAnchor, constant: -8),
            table.bottomAnchor.constraint(lessThanOrEqualTo: safeAreaLayoutGuide.bottomAnchor, constant: -8),
            empty.centerYAnchor.constraint(equalTo: centerYAnchor, constant: 21),   // under the header
            empty.leadingAnchor.constraint(equalTo: leadingAnchor, constant: 24),
            empty.trailingAnchor.constraint(equalTo: trailingAnchor, constant: -24),
        ])
    }
    required init?(coder: NSCoder) { fatalError("not used") }

    /// The card: as tall as its rows (#626).
    private final class Card: UITableView {
        override var contentSize: CGSize { didSet { invalidateIntrinsicContentSize() } }
        override var intrinsicContentSize: CGSize { CGSize(width: UIView.noIntrinsicMetric, height: contentSize.height) }
    }

    /// A row on the card, `text` in the label's colour or the hint's while `off` (#626).
    static func card(_ cell: UITableViewCell, _ content: inout UIListContentConfiguration, off: Bool = false) {
        cell.backgroundColor = .clear
        content.textProperties.color = off ? Style.hint : Style.label
        content.secondaryTextProperties.color = Style.hint
    }
}

/// The history in the keys' place (#597), as Gboard's: the toolbar's clipboard key opens it,
/// a pick or the keyboard button closes it (`SuggestionBar.showClips`). Rows newest first:
/// two lines of text or a thumbnail, each with a pin and a delete; Clear all keeps the
/// pinned. Its Paste (the system's control, text or images) keeps a clip copied elsewhere,
/// shown only while there is one not kept yet (`ClipboardHistory.fresh`).
final class ClipboardPanel: KeysPanel, UITableViewDataSource, UITableViewDelegate {
    let history: ClipboardHistory
    let pasteboard: UIPasteboard
    var onPick: ((ClipboardHistory.Clip) -> Void)?
    private(set) var clips: [ClipboardHistory.Clip] = []
    let clearButton = UIButton(configuration: .plain())
    let pasteControl: UIPasteControl = {
        let config = UIPasteControl.Configuration()
        config.displayMode = .iconAndLabel
        config.baseForegroundColor = TerminalKeyboard.Style.accent
        config.baseBackgroundColor = TerminalKeyboard.Style.surface
        let control = UIPasteControl(configuration: config)
        control.maximumContentSizeCategory = .large   // larger draws blank, as the bar's
        return control
    }()

    init(history: ClipboardHistory, pasteboard: UIPasteboard) {
        self.history = history
        self.pasteboard = pasteboard
        super.init(title: "Clipboard", empty: "What you copy or paste shows here.", trailing: [pasteControl, clearButton])
        pasteConfiguration = UIPasteConfiguration(acceptableTypeIdentifiers: [UTType.plainText.identifier,
                                                                              UTType.image.identifier])
        pasteControl.target = self
        clearButton.configuration?.title = "Clear all"
        clearButton.configuration?.baseForegroundColor = Style.accent
        clearButton.accessibilityHint = "Keeps the pinned ones"
        clearButton.addAction(UIAction { [weak self] _ in self?.history.clear(); self?.reload() }, for: .touchUpInside)
        table.dataSource = self
        table.delegate = self
        let width = pasteControl.widthAnchor.constraint(equalToConstant: 96)
        width.priority = .defaultHigh   // gives way to the stack's zero width while hidden
        NSLayoutConstraint.activate([width, pasteControl.heightAnchor.constraint(equalToConstant: 36)])
        reload()
    }
    required init?(coder: NSCoder) { fatalError("not used") }

    func reload() {
        clips = history.clips
        pasteControl.isHidden = !history.fresh(pasteboard)
        clearButton.isEnabled = clips.contains { !$0.pinned }
        empty.isHidden = !clips.isEmpty
        table.reloadData()
    }

    override func paste(itemProviders: [NSItemProvider]) {
        history.capture(itemProviders, from: pasteboard) { [weak self] in self?.reload() }
    }

    func tableView(_ tableView: UITableView, numberOfRowsInSection section: Int) -> Int { clips.count }

    func tableView(_ tableView: UITableView, cellForRowAt indexPath: IndexPath) -> UITableViewCell {
        let clip = clips[indexPath.row]
        let cell = UITableViewCell(style: .default, reuseIdentifier: nil)
        var content = cell.defaultContentConfiguration()
        Self.card(cell, &content)
        content.textProperties.numberOfLines = 2
        content.textProperties.font = .systemFont(ofSize: 15)
        if let text = clip.text {
            content.text = text
            cell.accessibilityLabel = text
            cell.accessibilityHint = "Types it and copies it"
        } else {
            content.image = history.thumbnail(clip, side: 88 * max(1, traitCollection.displayScale))
            content.imageProperties.maximumSize = CGSize(width: 88, height: 88)
            content.imageProperties.cornerRadius = 6
            cell.accessibilityLabel = "Image"
            cell.accessibilityHint = "Copies it, to paste"
        }
        cell.contentConfiguration = content
        cell.isAccessibilityElement = true
        cell.accessibilityValue = clip.pinned ? "pinned" : nil
        let pin = UIButton(configuration: .plain())
        pin.configuration?.image = UIImage(systemName: clip.pinned ? "pin.fill" : "pin")
        pin.configuration?.baseForegroundColor = clip.pinned ? Style.accent : Style.hint
        pin.accessibilityLabel = clip.pinned ? "Unpin" : "Pin"
        pin.addAction(UIAction { [weak self] _ in self?.history.pin(clip.id, !clip.pinned); self?.reload() },
                      for: .touchUpInside)
        let delete = UIButton(configuration: .plain())
        delete.configuration?.image = UIImage(systemName: "xmark")
        delete.configuration?.baseForegroundColor = Style.hint
        delete.accessibilityLabel = "Delete"
        delete.addAction(UIAction { [weak self] _ in self?.history.delete(clip.id); self?.reload() }, for: .touchUpInside)
        let actions = UIStackView(arrangedSubviews: [pin, delete])
        actions.frame = CGRect(x: 0, y: 0, width: 88, height: 44)
        actions.distribution = .fillEqually
        cell.accessoryView = actions
        cell.accessibilityCustomActions = [
            UIAccessibilityCustomAction(name: pin.accessibilityLabel ?? "Pin") { [weak self] _ in
                self?.history.pin(clip.id, !clip.pinned); self?.reload(); return true
            },
            UIAccessibilityCustomAction(name: "Delete") { [weak self] _ in
                self?.history.delete(clip.id); self?.reload(); return true
            },
        ]
        return cell
    }

    func tableView(_ tableView: UITableView, didSelectRowAt indexPath: IndexPath) {
        onPick?(clips[indexPath.row])
    }
}
